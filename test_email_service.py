async def main():
    """Run all tests"""
    print("\n" + "="*70)
    print("📧 EMAIL NOTIFICATION SERVICE - TEST SUITE")
    print("="*70)
    
    # Check configuration
    print("\n📋 Configuration Status:")
    print(f"   Notifications Enabled: {EXTRACTION_NOTIFICATIONS_ENABLED}")
    print(f"   Client ID: {OUTLOOK_CLIENT_ID[:20]}..." if OUTLOOK_CLIENT_ID else "   Client ID: NOT SET")
    print(f"   Tenant ID: {OUTLOOK_TENANT_ID[:20]}..." if OUTLOOK_TENANT_ID else "   Tenant ID: NOT SET")
    print(f"   Token Cache: {OUTLOOK_TOKEN_CACHE_PATH}")
    print(f"   TO Recipients: {NOTIFICATION_RECIPIENTS_TO}")
    print(f"   CC Recipients: {NOTIFICATION_RECIPIENTS_CC}")
    
    if not EXTRACTION_NOTIFICATIONS_ENABLED:
        print("\n⚠️  WARNING: Email notifications are DISABLED in config.yaml")
        print("   Set 'extraction_notifications.enabled: true' to enable")
        return
    
    if not NOTIFICATION_RECIPIENTS_TO:
        print("\n⚠️  WARNING: No TO recipients configured!")
        print("   Please add email addresses in config.yaml under:")
        print("   extraction_notifications.recipients.to_recipients")
        print("\n   Continuing with placeholder email for testing...")
    
    print("\n" + "="*70)
    print("🚀 STARTING TESTS")
    print("="*70)
    print("\nNote: On first run, a browser window will open for authentication.")
    print("Login with your Microsoft 365 account to authorize email sending.")
    print("\nPress Enter to continue...")
    input()
    
    # Run tests
    results = []
    
    # Test 1
    results.append(await test_simple_email())
    await asyncio.sleep(2)
    
    # Test 2
    results.append(await test_html_email())
    await asyncio.sleep(2)
    
    # Test 3
    results.append(await test_email_with_attachment())
    await asyncio.sleep(2)
    
    # Test 4
    results.append(await test_full_notification())
    
    # Summary
    print("\n" + "="*70)
    print("📊 TEST SUMMARY")
    print("="*70)
    print(f"   Simple Email:        {'✅ PASS' if results[0] else '❌ FAIL'}")
    print(f"   HTML Email:          {'✅ PASS' if results[1] else '❌ FAIL'}")
    print(f"   Email w/ Attachment: {'✅ PASS' if results[2] else '❌ FAIL'}")
    print(f"   Full Notification:   {'✅ PASS' if results[3] else '❌ FAIL'}")
    print("="*70)
    
    passed = sum(results)
    total = len(results)
    
    if passed == total:
        print(f"\n🎉 ALL TESTS PASSED ({passed}/{total})")
        print("\n✅ Your email notification service is fully operational!")
        print("   You can now run the extraction bot with confidence.")
    else:
        print(f"\n⚠️  SOME TESTS FAILED ({passed}/{total} passed)")
        print("\n   Please check the error messages above and:")
        print("   1. Verify your config.yaml settings")
        print("   2. Check Azure AD app permissions")
        print("   3. Ensure network connectivity")
        print("   4. Review EMAIL_NOTIFICATION_SETUP.md for troubleshooting")
    
    print("\n" + "="*70)


if __name__ == "__main__":
    asyncio.run(main())
