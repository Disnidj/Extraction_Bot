async def test_email_with_attachment():
    """Test 3: Send an email with attachment"""
    print("\n" + "="*70)
    print("TEST 3: Email with Attachment")
    print("="*70)
    
    # Create a test file
    test_file = Path("test_attachment.txt")
    test_file.write_text("This is a test attachment file.\n\nGenerated by: Extraction Bot Email Service Test\nDate: " + datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    
    try:
        success = await send_email_async(
            subject="📎 Test Email with Attachment - Extraction Bot",
            body="<h2>Attachment Test</h2><p>This email includes a test text file attachment.</p><p>If you receive the attachment, the file attachment feature is working correctly!</p>",
            to=NOTIFICATION_RECIPIENTS_TO[:1] if NOTIFICATION_RECIPIENTS_TO else ["test@example.com"],
            attachments=[test_file],
            client_id=OUTLOOK_CLIENT_ID,
            tenant_id=OUTLOOK_TENANT_ID,
            cache_path=OUTLOOK_TOKEN_CACHE_PATH,
        )
        
        if success:
            print("✅ Email with attachment sent successfully!")
            # Clean up test file
            test_file.unlink()
            return True
        else:
            print("❌ Failed to send email with attachment")
            # Clean up test file
            if test_file.exists():
                test_file.unlink()
            return False
            
    except Exception as e:
        print(f"❌ Error sending email with attachment: {e}")
        import traceback
        traceback.print_exc()
        # Clean up test file
        if test_file.exists():
            test_file.unlink()
        return False


